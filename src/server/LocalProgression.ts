import { GameType } from "@openfront/engine-api/game/GameTypes";
import { maps } from "@openfront/engine-api/game/Maps.gen";
import {
  GameConfigSchema,
  type GameConfig,
} from "@openfront/engine-api/Schemas";
import {
  type GameXpResponse,
  type Progress,
  type ProgressionConfig,
  type PublicProgress,
  type XpRules,
} from "@openfront/shared/ApiSchemas";
import {
  GameEndInfoSchema,
  type GameEndInfo,
} from "@openfront/shared/WireSchemas";
import {
  computeXp,
  ffaOutlasted,
  PROVISIONAL_XP_FORMULA,
} from "@openfront/shared/Xp";
import { DatabaseSync } from "node:sqlite";
import { z } from "zod";

// Same formula as upstream, with private lobbies open to small groups and AI games.
export const LOCAL_XP_RULES: XpRules = {
  minAliveTicks: 1200,
  gameXp: 50,
  xpPerMinute: 17,
  timeCapMinutes: 30,
  ffaPlacementMax: 150,
  ffaWin: 300,
  fullLobbyHumans: 20,
  teamWin: 150,
  teamWinMinAlivePermille: 500,
  hvnWin: 100,
  firstGameOfDay: 100,
  featXp: 0,
  maxFeatsPerGame: 3,
  publicPermille: 1000,
  rankedPermille: 1000,
  privatePermille: 500,
  singleplayerPermille: 250,
  privateMinHumans: 1,
  privateGamesPerDay: 10,
  singleplayerGamesPerDay: 5,
};
export const LOCAL_PROGRESSION_CONFIG: ProgressionConfig = {
  version: 1,
  maxLevel: 100,
  maxPrestige: 0,
  formula: PROVISIONAL_XP_FORMULA,
  requireStatsAgreed: true,
  scoresSingleplayer: true,
  xp: LOCAL_XP_RULES,
  levels: Array.from({ length: 100 }, (_, i) => ({
    level: i + 1,
    xpToNext: i === 99 ? 0 : 250 + i * 50,
    cumulativeXp: i * 250 + (i * (i - 1) * 50) / 2,
  })),
  flares: [],
};

export const LocalProgressionMatchSchema = z.object({
  info: GameEndInfoSchema.extend({
    players: GameEndInfoSchema.shape.players.max(1000),
    num_turns: z.number().int().min(0).max(216000),
  }),
  // Generated by the game server from authenticated, non-kicked local players.
  userIds: z.array(z.uuid()).max(1000),
  leftAt: z.record(z.string(), z.number().int().min(0).max(216000)).default({}),
  disqualified: z.boolean().default(false),
});
export type LocalProgressionMatch = z.infer<typeof LocalProgressionMatchSchema>;

type Daily = {
  privateGames: number;
  singleplayerGames: number;
  firstGameClaimed: boolean;
};
const noDaily = (): Daily => ({
  privateGames: 0,
  singleplayerGames: 0,
  firstGameClaimed: false,
});
const dayOf = (now: number) => new Date(now).toISOString().slice(0, 10);
const SIX_HOURS = 6 * 60 * 60 * 1000;

/** Persistent XP only. This never changes Caps, owned cosmetics or map medals. */
export class LocalProgression {
  constructor(private readonly db: DatabaseSync) {
    db.exec(`
      CREATE TABLE IF NOT EXISTS player_xp (
        user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        lifetime_xp INTEGER NOT NULL DEFAULT 0 CHECK(lifetime_xp >= 0));
      CREATE TABLE IF NOT EXISTS xp_games (
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        game_id TEXT NOT NULL, result TEXT NOT NULL, PRIMARY KEY(user_id, game_id));
      CREATE TABLE IF NOT EXISTS xp_daily (
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        day TEXT NOT NULL, state TEXT NOT NULL, PRIMARY KEY(user_id, day));
      CREATE TABLE IF NOT EXISTS xp_solo_starts (
        user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
        game_id TEXT NOT NULL, config TEXT NOT NULL, started_at INTEGER NOT NULL);
      CREATE TABLE IF NOT EXISTS xp_milestones (
        user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        level INTEGER NOT NULL, at TEXT NOT NULL, PRIMARY KEY(user_id, level));
    `);
  }

  private daily(userId: string, now: number): Daily {
    const row = this.db
      .prepare("SELECT state FROM xp_daily WHERE user_id=? AND day=?")
      .get(userId, dayOf(now)) as { state: string } | undefined;
    return row ? (JSON.parse(row.state) as Daily) : noDaily();
  }

  progress(userId: string, now = Date.now()): Progress {
    const row = this.db
      .prepare("SELECT lifetime_xp FROM player_xp WHERE user_id=?")
      .get(userId) as { lifetime_xp: number } | undefined;
    const lifetimeXp = row?.lifetime_xp ?? 0;
    const level = [...LOCAL_PROGRESSION_CONFIG.levels]
      .reverse()
      .find((entry) => entry.cumulativeXp <= lifetimeXp)!;
    return {
      prestige: 0,
      level: level.level,
      lifetimeXp,
      xpInLevel: level.xpToNext === 0 ? 0 : lifetimeXp - level.cumulativeXp,
      xpForNext: level.xpToNext,
      canPrestige: false,
      legend: level.level === 100,
      subscriberPermille: 1000,
      daily: { day: dayOf(now), ...this.daily(userId, now) },
    };
  }

  publicProgress(userId: string, now = Date.now()): PublicProgress {
    const { level, prestige, lifetimeXp, legend, xpInLevel, xpForNext } =
      this.progress(userId, now);
    const milestones = this.db
      .prepare(
        "SELECT level, at FROM xp_milestones WHERE user_id=? ORDER BY level",
      )
      .all(userId) as { level: number; at: string }[];
    return {
      level,
      prestige,
      lifetimeXp,
      legend,
      xpInLevel,
      xpForNext,
      prestigeHistory: [],
      milestones: milestones.map((entry) => ({ ...entry, prestige: 0 })),
    };
  }

  game(userId: string, gameId: string): GameXpResponse | null {
    const row = this.db
      .prepare("SELECT result FROM xp_games WHERE user_id=? AND game_id=?")
      .get(userId, gameId) as { result: string } | undefined;
    return row ? (JSON.parse(row.result) as GameXpResponse) : null;
  }

  startSolo(
    userId: string,
    gameId: string,
    config: GameConfig,
    now = Date.now(),
  ): boolean {
    if (config.gameType !== GameType.Singleplayer || this.game(userId, gameId))
      return false;
    const encoded = JSON.stringify(GameConfigSchema.parse(config));
    const row = this.db
      .prepare("SELECT game_id, config FROM xp_solo_starts WHERE user_id=?")
      .get(userId) as { game_id: string; config: string } | undefined;
    if (row?.game_id === gameId) return row.config === encoded;
    this.db
      .prepare(`INSERT INTO xp_solo_starts VALUES (?, ?, ?, ?)
      ON CONFLICT(user_id) DO UPDATE SET game_id=excluded.game_id, config=excluded.config, started_at=excluded.started_at`)
      .run(userId, gameId, encoded, now);
    return true;
  }

  finishSolo(
    userId: string,
    value: unknown,
    now = Date.now(),
  ): GameXpResponse | null {
    const parsed = GameEndInfoSchema.safeParse(value);
    if (!parsed.success) return null;
    const info = parsed.data;
    const previous = this.game(userId, info.gameID);
    if (previous) return previous;
    const start = this.db
      .prepare(
        "SELECT game_id, config, started_at FROM xp_solo_starts WHERE user_id=?",
      )
      .get(userId) as
      | { game_id: string; config: string; started_at: number }
      | undefined;
    // A browser may submit only its own registered solo game, never a multiplayer result.
    if (
      !start ||
      start.game_id !== info.gameID ||
      info.config.gameType !== GameType.Singleplayer ||
      info.players.length !== 1 ||
      info.players[0].persistentID !== userId ||
      JSON.stringify(info.config) !== start.config
    )
      return null;
    const elapsed = now - start.started_at;
    // Solo is client-reported. Bound simulated time by the server clock, and cap daily games.
    if (
      elapsed < 0 ||
      elapsed > SIX_HOURS ||
      !Number.isInteger(info.num_turns) ||
      info.num_turns <= 0 ||
      info.num_turns > Math.floor(elapsed / 100) + 50 ||
      info.end <= info.start ||
      info.end - info.start > elapsed + 5000
    )
      return null;
    return this.transaction(() =>
      this.score(userId, info, new Map(), false, now),
    );
  }

  awardMatch(match: LocalProgressionMatch, now = Date.now()): void {
    if (match.info.config.gameType === GameType.Singleplayer) return;
    this.transaction(() => {
      for (const userId of new Set(match.userIds)) {
        if (!this.db.prepare("SELECT 1 FROM users WHERE id=?").get(userId))
          continue;
        if (
          !match.info.players.some((player) => player.persistentID === userId)
        )
          continue;
        this.score(
          userId,
          match.info,
          new Map(Object.entries(match.leftAt)),
          match.disqualified,
          now,
        );
      }
    });
  }

  private score(
    userId: string,
    info: GameEndInfo,
    leftAt: Map<string, number>,
    disqualified: boolean,
    now: number,
  ): GameXpResponse {
    const previous = this.game(userId, info.gameID);
    if (previous) return previous;
    const before = this.progress(userId, now);
    const me = info.players.find((player) => player.persistentID === userId)!;
    const spawned = info.players.filter((player) => player.stats !== undefined);
    const map = maps.find((entry) => entry.type === info.config.gameMap);
    const hasOpponents =
      spawned.length > 1 ||
      info.config.bots > 0 ||
      (info.config.nations === "default"
        ? (map?.defaultNationCount ?? 0) > 0
        : Number(info.config.nations) > 0);
    const winners =
      info.winner?.[0] === "player"
        ? info.winner.slice(1)
        : (info.winner?.slice(2) ?? []);
    const verified =
      info.config.gameType === GameType.Singleplayer ||
      info.statsAgreed === true;
    const outlasted = ffaOutlasted(
      spawned.map((player) => ({
        clientID: player.clientID,
        stats: player.stats,
      })),
      info.num_turns,
      leftAt,
    );
    const result = !verified
      ? { eligible: false as const, reason: "unverified" }
      : disqualified
        ? { eligible: false as const, reason: "custom_settings" }
        : !hasOpponents
          ? { eligible: false as const, reason: "too_few_humans" }
          : computeXp(
              {
                config: info.config,
                stats: me.stats,
                ticks: info.num_turns,
                leftAtTick: leftAt.get(me.clientID) ?? null,
                isWinner: winners.includes(me.clientID),
                spawnedHumans: spawned.length,
                opponentsOutlasted: outlasted.get(me.clientID) ?? 0,
                featCount: 0,
                daily: this.daily(userId, now),
                subscriberPermille: 1000,
              },
              LOCAL_XP_RULES,
            );
    let response: GameXpResponse;
    if (!result.eligible)
      response = {
        gameId: info.gameID,
        eligible: false,
        reason: result.reason,
      };
    else {
      this.db
        .prepare(`INSERT INTO player_xp VALUES (?, ?) ON CONFLICT(user_id)
        DO UPDATE SET lifetime_xp=lifetime_xp+excluded.lifetime_xp`)
        .run(userId, result.breakdown.total);
      this.db
        .prepare(`INSERT INTO xp_daily VALUES (?, ?, ?) ON CONFLICT(user_id, day)
        DO UPDATE SET state=excluded.state`)
        .run(userId, dayOf(now), JSON.stringify(result.daily));
      const after = this.progress(userId, now);
      const levelsReached = Array.from(
        { length: after.level - before.level },
        (_, i) => ({ prestige: 0, level: before.level + i + 1 }),
      );
      for (const { level } of levelsReached) {
        if ([10, 25, 50, 75, 100].includes(level))
          this.db
            .prepare("INSERT OR IGNORE INTO xp_milestones VALUES (?, ?, ?)")
            .run(userId, level, new Date(now).toISOString());
      }
      response = {
        gameId: info.gameID,
        eligible: true,
        breakdown: result.breakdown,
        before: {
          prestige: before.prestige,
          level: before.level,
          xpInLevel: before.xpInLevel,
          xpForNext: before.xpForNext,
        },
        after,
        levelsReached,
        rewards: [],
        flares: [],
      };
    }
    this.db
      .prepare("INSERT INTO xp_games VALUES (?, ?, ?)")
      .run(userId, info.gameID, JSON.stringify(response));
    return response;
  }

  private transaction<T>(action: () => T): T {
    this.db.exec("BEGIN IMMEDIATE");
    try {
      const result = action();
      this.db.exec("COMMIT");
      return result;
    } catch (error) {
      this.db.exec("ROLLBACK");
      throw error;
    }
  }
}
